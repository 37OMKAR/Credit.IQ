"""ICAI UDIN (Unique Document Identification Number) extraction and validation engine.

Per ICAI Council guidelines:
- UDIN has been made mandatory for all Corporate Audit reports, Tax Audits, and Financial Statements
  issued by Chartered Accountants in India with effect from 1 July 2019.
- Structure of an 18-character ICAI UDIN:
    Characters 1-2   : Year of UDIN generation (e.g., '21' for 2021, '24' for 2024).
    Characters 3-8   : 6-digit ICAI Membership Number of the signing CA (zero-padded if 5 digits).
    Characters 9-18  : 10-character alphanumeric security code/hash generated by the ICAI portal.

Validation Rules:
1. Syntax: Must be exactly 18 alphanumeric characters.
2. Membership cross-check: The 6-digit substring (digits 3-8) must match the CA Membership Number
   extracted from the signature block on the Independent Auditor's Report or Balance Sheet.
3. Year plausibility: The 2-digit year prefix (digits 1-2) must match the signing date of the audit report.
4. Mandatory Audit Check: Any financial statements for FY 2019-20 or later that are marked as 'audited'
   MUST bear an ICAI UDIN. Absence of UDIN is flagged as a high-severity governance red flag.

Verification Portal:
- Official ICAI Verification URL: https://udin.icai.org/search-udin
"""
import re
from typing import Dict, List, Optional, Tuple

ICAI_PORTAL_URL = "https://udin.icai.org/search-udin"

# Explicit UDIN patterns (preceded by label)
_UDIN_EXPLICIT_RE = re.compile(
    r"\bUDIN\s*[:\-\.]?\s*([0-9]{2}[0-9]{6}[A-Z0-9]{10})\b",
    re.I
)

# Standalone 18-char alphanumeric pattern matching ICAI format:
# 2-digit year (19 to 35) + 6-digit membership + 10-char alphanumeric string
_UDIN_STANDALONE_RE = re.compile(
    r"\b(19|2[0-9]|3[0-5])(\d{6})([A-Z0-9]{10})\b"
)

# CA Membership Number patterns
_MEMBERSHIP_RE = re.compile(
    r"\b(?:Membership\s*No\.?|M\.?\s*No\.?|Mem\.?\s*No\.?)\s*[:\-\.]?\s*(\d{5,6})\b",
    re.I
)

# Firm Registration Number (FRN) patterns (e.g., 313105E, 309090E, 5268C, 100000W)
_FRN_RE = re.compile(
    r"\b(?:FRN|Firm[\'\’\s]*s?\s*Reg(?:istration|n)?\.?\s*No\.?)\s*[:\-\.]?\s*([0-9A-Z]{4,8})\b",
    re.I
)

# Date of signing patterns
_DATE_RE = re.compile(
    r"\bDate\s*[:\-\.]?\s*(\d{1,2}(?:st|nd|rd|th)?\s+[A-Za-z]+\s*,?\s*\d{4}|[A-Za-z]+\s+\d{1,2}(?:st|nd|rd|th)?\s*,?\s*\d{4}|\d{1,2}[\-\./]\d{1,2}[\-\./]\d{2,4})\b",
    re.I
)

# CA Name patterns (near Partner / Chartered Accountant)
_CA_NAME_RE = re.compile(
    r"(?:C\.?A\.?\s+|Chartered\s+Accountants?\s+)([A-Z\s\.,]{3,35})(?:\n|$|Partner)",
    re.I
)


def extract_ca_signatures(pages: List[Dict]) -> List[Dict]:
    """Scan all pages for Chartered Accountant signature blocks.
    
    Returns a list of dicts with:
      - ca_name: str
      - membership_no: str (6-digit normalized)
      - firm_name: str
      - frn: str
      - date: str
      - page: int
    """
    signatures = []
    seen_memberships = set()

    for p in pages:
        text = p.get("text") or ""
        if not text.strip():
            continue

        p_num = p.get("page", 1)
        lines = [line.strip() for line in text.splitlines() if line.strip()]

        for i, line in enumerate(lines):
            mem_m = _MEMBERSHIP_RE.search(line)
            if mem_m:
                raw_mem = mem_m.group(1)
                norm_mem = raw_mem.zfill(6)
                if norm_mem in seen_memberships:
                    continue

                # Context window around the membership number line
                start = max(0, i - 6)
                end = min(len(lines), i + 5)
                ctx_lines = lines[start:end]
                ctx_text = " ".join(ctx_lines)

                # Look for FRN
                frn_m = _FRN_RE.search(ctx_text)
                frn = frn_m.group(1).upper() if frn_m else ""

                # Look for Date
                date_m = _DATE_RE.search(ctx_text)
                date_str = date_m.group(1) if date_m else ""

                # Look for CA Name immediately above the membership line
                ca_name = ""
                for j in range(i - 1, max(-1, i - 4), -1):
                    cl = lines[j]
                    if re.search(r"^\(?\s*(?:Partner|Proprietor|Member)\s*\)?$", cl, re.I):
                        continue
                    cleaned = re.sub(r"^(?:C\.?A\.?\s*|\(?CA\)?\s*)", "", cl, flags=re.I).strip()
                    if cleaned and len(cleaned) > 2 and not re.search(r"(?:FRN|Firm|For\s+|Membership|Chartered)", cleaned, re.I):
                        ca_name = cleaned
                        break

                # Look for Firm Name and FRN in surrounding lines
                firm_name = ""
                for cl in ctx_lines:
                    if re.search(r"\b(audit trail|tampered|preserved|statutory requirement|record retention|board of directors|accompanying|integral part)\b", cl, re.I):
                        continue
                    m_firm = re.search(r"^(?:For\s+)?([A-Z\s\.,&]{4,60}(?:LLP|Associates|Co\.|Company))", cl, re.I)
                    if m_firm:
                        cleaned_firm = m_firm.group(1).strip()
                        firm_name = cleaned_firm
                        break

                signatures.append({
                    "ca_name": ca_name,
                    "membership_no": norm_mem,
                    "firm_name": firm_name,
                    "frn": frn,
                    "date": date_str,
                    "page": p_num,
                })
                seen_memberships.add(norm_mem)

    return signatures


def extract_udins(pages: List[Dict]) -> List[Dict]:
    """Scan pages for 18-character ICAI UDINs.
    
    Returns a list of dicts with:
      - udin: str (18 chars uppercase)
      - page: int
      - method: 'explicit_label' | 'pattern_match'
    """
    found = []
    seen = set()

    for p in pages:
        text = p.get("text") or ""
        if not text.strip():
            continue
        p_num = p.get("page", 1)

        # 1. Look for explicit UDIN labels
        for m in _UDIN_EXPLICIT_RE.finditer(text):
            u = m.group(1).upper()
            if u not in seen and len(u) == 18:
                seen.add(u)
                found.append({"udin": u, "page": p_num, "method": "explicit_label"})

        # 2. Look for standalone 18-char strings if near audit / CA terms
        if not found and re.search(r"\b(auditor|chartered accountant|icai|balance sheet|report)\b", text, re.I):
            for m in _UDIN_STANDALONE_RE.finditer(text):
                u = m.group(0).upper()
                if u not in seen and len(u) == 18:
                    seen.add(u)
                    found.append({"udin": u, "page": p_num, "method": "pattern_match"})

    return found


def validate_udin(
    udin_str: str,
    ca_signatures: Optional[List[Dict]] = None,
    doc_year: Optional[int] = None,
    doc_date: Optional[str] = None
) -> Dict:
    """Validate an 18-character ICAI UDIN string against ICAI syntax, signing CA, and year.
    
    Returns a structured audit dict:
      - udin: str
      - is_valid: bool
      - status: 'VALID' | 'FORMAT_VALID_UNMATCHED_CA' | 'YEAR_MISMATCH' | 'MALFORMED'
      - year_code: str (e.g. '21')
      - ca_membership_no: str (e.g. '062081')
      - security_code: str (10 chars)
      - matched_ca: dict or None
      - portal_url: str
      - message: str
    """
    u = (udin_str or "").strip().upper()
    ca_signatures = ca_signatures or []

    if len(u) != 18 or not re.match(r"^[0-9]{8}[A-Z0-9]{10}$", u):
        return {
            "udin": u,
            "is_valid": False,
            "status": "MALFORMED",
            "year_code": u[:2] if len(u) >= 2 else "",
            "ca_membership_no": u[2:8] if len(u) >= 8 else "",
            "security_code": u[8:] if len(u) > 8 else "",
            "matched_ca": None,
            "portal_url": ICAI_PORTAL_URL,
            "message": f"Malformed UDIN '{u}': must be exactly 18 alphanumeric characters per ICAI format."
        }

    year_code = u[:2]
    udin_mem = u[2:8]
    sec_code = u[8:]

    # Cross-check CA membership number
    matched_ca = None
    if ca_signatures:
        for ca in ca_signatures:
            if ca.get("membership_no") == udin_mem:
                matched_ca = ca
                break

    # Year cross-check
    year_mismatch = False
    ref_year = None
    if doc_date:
        ym = re.search(r"\b(20\d\d)\b", doc_date)
        if ym:
            ref_year = int(ym.group(1)) % 100
    elif doc_year:
        ref_year = int(str(doc_year)[:4]) % 100

    if ref_year is not None:
        try:
            u_yr = int(year_code)
            # Allow up to 1 year gap (e.g., FY21 audited in late 2021 or early 2022)
            if abs(u_yr - ref_year) > 1:
                year_mismatch = True
        except ValueError:
            pass

    if ca_signatures and not matched_ca:
        available_mems = ", ".join(ca.get("membership_no", "") for ca in ca_signatures if ca.get("membership_no"))
        return {
            "udin": u,
            "is_valid": False,
            "status": "FORMAT_VALID_UNMATCHED_CA",
            "year_code": year_code,
            "ca_membership_no": udin_mem,
            "security_code": sec_code,
            "matched_ca": None,
            "portal_url": ICAI_PORTAL_URL,
            "message": (
                f"UDIN CA Membership '{udin_mem}' does NOT match any signing auditor in the document "
                f"(found: {available_mems or 'none'}). Potential unauthorized or mismatched UDIN."
            )
        }

    if year_mismatch:
        return {
            "udin": u,
            "is_valid": False,
            "status": "YEAR_MISMATCH",
            "year_code": year_code,
            "ca_membership_no": udin_mem,
            "security_code": sec_code,
            "matched_ca": matched_ca,
            "portal_url": ICAI_PORTAL_URL,
            "message": f"UDIN generation year '20{year_code}' conflicts with statement signing year '20{ref_year}'."
        }

    ca_name_str = f" for {matched_ca['ca_name']}" if matched_ca and matched_ca.get("ca_name") else ""
    return {
        "udin": u,
        "is_valid": True,
        "status": "VALID",
        "year_code": year_code,
        "ca_membership_no": udin_mem,
        "security_code": sec_code,
        "matched_ca": matched_ca,
        "portal_url": ICAI_PORTAL_URL,
        "message": f"Valid 18-character ICAI UDIN{ca_name_str} (CA M.No. {udin_mem}, Generated 20{year_code})."
    }


def audit_udin_compliance(
    pages: List[Dict],
    years: List[str],
    notes: Optional[Dict] = None,
    is_audited: bool = True
) -> Dict:
    """Comprehensive ICAI UDIN compliance check for loan underwriting.
    
    Evaluates:
      1. Extracted CA signature blocks (CAs, M.Nos, FRNs, Dates).
      2. Extracted UDINs.
      3. Compliance status:
         - PASS: Valid UDIN found and matches signing CA.
         - MISSING_MANDATORY: Statement is FY 2019-20 or later, audited, but NO UDIN found.
         - FORMAT_VALID_UNMATCHED_CA: UDIN present but CA membership mismatch.
         - NOT_APPLICABLE: Pre-July 2019 statements or provisional accounts.
    """
    ca_signatures = extract_ca_signatures(pages)
    udins_found = extract_udins(pages)
    notes = notes or {}

    # Determine earliest and latest financial year
    fy_ints = []
    for y in years:
        m = re.search(r"(20\d\d)", str(y))
        if m:
            fy_ints.append(int(m.group(1)))
    latest_fy = max(fy_ints) if fy_ints else 2021

    # ICAI mandate date check: mandatory for all audit reports from 1 July 2019 (FY 2019-20 onwards)
    is_mandatory = is_audited and latest_fy >= 2020

    if not udins_found:
        if is_mandatory:
            msg = (
                f"Missing ICAI UDIN: Financial statements for FY {latest_fy} are audited but bear NO ICAI "
                f"Unique Document Identification Number (UDIN). Under ICAI mandate effective 1 July 2019, all "
                f"audited reports and balance sheets signed by Chartered Accountants must bear an 18-digit UDIN. "
                f"Statements lacking a UDIN may be unfiled drafts, uncertified copies, or counterfeit."
            )
            return {
                "has_udin": False,
                "is_mandatory": True,
                "status": "MISSING_MANDATORY",
                "udins": [],
                "primary_udin": None,
                "ca_signatures": ca_signatures,
                "message": msg,
                "portal_url": ICAI_PORTAL_URL,
                "red_flag": {
                    "title": "Missing ICAI UDIN on Audited Balance Sheet",
                    "category": "Audit & Compliance",
                    "severity": "High",
                    "evidence": f"Audited statements (FY {latest_fy}) signed without printed 18-digit ICAI UDIN",
                    "why": "Unauthenticated accounts; cannot verify whether the audit was genuinely filed with ICAI.",
                    "action": f"Demand the official ICAI UDIN certificate and verify on {ICAI_PORTAL_URL} before sanction."
                }
            }
        else:
            return {
                "has_udin": False,
                "is_mandatory": False,
                "status": "NOT_APPLICABLE",
                "udins": [],
                "primary_udin": None,
                "ca_signatures": ca_signatures,
                "message": f"UDIN not mandatory for FY {latest_fy} (prior to ICAI mandate of 1 July 2019) or unaudited figures.",
                "portal_url": ICAI_PORTAL_URL,
                "red_flag": None
            }

    # Validate each found UDIN
    validated_list = []
    doc_date = ca_signatures[0].get("date") if ca_signatures else None
    for u_item in udins_found:
        v = validate_udin(u_item["udin"], ca_signatures=ca_signatures, doc_year=latest_fy, doc_date=doc_date)
        v["page"] = u_item["page"]
        validated_list.append(v)

    primary = validated_list[0]
    red_flag = None

    if primary["status"] == "FORMAT_VALID_UNMATCHED_CA":
        red_flag = {
            "title": "UDIN CA Membership Mismatch",
            "category": "Audit & Compliance",
            "severity": "High",
            "evidence": f"UDIN {primary['udin']} contains CA M.No {primary['ca_membership_no']}, which does not match signing auditor.",
            "why": "Potential fraudulent insertion of another CA's UDIN to bypass validation.",
            "action": f"Halt processing and verify directly on {ICAI_PORTAL_URL} with the signing CA firm."
        }
    elif primary["status"] == "MALFORMED":
        red_flag = {
            "title": "Malformed ICAI UDIN",
            "category": "Audit & Compliance",
            "severity": "High",
            "evidence": f"UDIN '{primary['udin']}' does not conform to 18-character ICAI syntax.",
            "why": "Fake or invalid UDIN string printed on document.",
            "action": f"Obtain certified audit copy with valid UDIN from borrower."
        }

    return {
        "has_udin": True,
        "is_mandatory": is_mandatory,
        "status": primary["status"],
        "udins": validated_list,
        "primary_udin": primary,
        "ca_signatures": ca_signatures,
        "message": primary["message"],
        "portal_url": ICAI_PORTAL_URL,
        "red_flag": red_flag
    }
